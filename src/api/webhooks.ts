/**
 * @swagger
 * /webhooks/{id}:
 *   patch:
 *     summary: Update a webhook subscription
 *     description: >
 *       Update the destination URL, event filters, or active state. Changing
 *       the URL resets verification — re-run `POST /webhooks/{id}/verify`.
 *       Deactivating a subscription immediately cancels pending deliveries.
 *     security:
 *       - ApiKeyAuth: []
 *     tags: [Webhooks]
 *     parameters:
 *       - in: path
 *         name: id
 *         required: true
 *         schema: { type: string }
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             properties:
 *               url: { type: string, format: uri }
 *               contractAddress: { type: string, nullable: true }
 *               eventType: { type: string, nullable: true }
 *               topicSymbol: { type: string, nullable: true }
 *               active: { type: boolean }
 *     responses:
 *       200:
 *         description: Updated subscription
 *       400:
 *         description: Validation error or blocked URL
 *       404:
 *         description: Not found or not owned by caller
 *       401:
 *         description: API key required
 */
webhooksRouter.patch(
  '/:id',
  asyncHandler(async (req: Request, res: Response) => {
    const parsed = updateSchema.safeParse(req.body);
    if (!parsed.success) return res.status(400).json({ error: parsed.error.flatten() });

    const existing = await prismaRead.webhookSubscription.findFirst({
      where: { id: req.params.id, apiKeyId: req.apiKey!.id },
    });
    if (!existing) return res.status(404).json({ error: 'Subscription not found' });

    const data: Prisma.WebhookSubscriptionUpdateInput = {};

    if (parsed.data.url !== undefined && parsed.data.url !== existing.url) {
      try {
        await assertSafeUrl(parsed.data.url);
      } catch (err) {
        const message = err instanceof SsrfBlockedError ? err.message : 'Invalid webhook URL';
        return res.status(400).json({ error: message });
      }
      data.url = parsed.data.url;
      // A new destination has not completed the handshake — reset verification.
      data.verified = false;
      data.verifiedAt = null;
      data.verificationToken = null;
      data.verificationExpiresAt = null;
    }

    if (parsed.data.contractAddress !== undefined) {
      data.contractAddress = parsed.data.contractAddress ?? null;
    }
    if (parsed.data.eventType !== undefined) {
      data.eventType = parsed.data.eventType ?? null;
    }
    if (parsed.data.topicSymbol !== undefined) {
      data.topicSymbol = parsed.data.topicSymbol ?? null;
    }
    if (parsed.data.active !== undefined) {
      data.active = parsed.data.active;
    }

    const sub = await prisma.webhookSubscription.update({
      where: { id: existing.id },
      data,
    });

    // When deactivating, immediately cancel all pending deliveries so the
    // retry loop doesn't attempt them before it notices the subscription is
    // inactive (#482).
    if (parsed.data.active === false) {
      await prisma.webhookDelivery.updateMany({
        where: { subscriptionId: sub.id, status: 'pending' },
        data: {
          status: 'cancelled',
          processingStatus: 'done',
          leaseExpiresAt: null,
          nextRetryAt: null,
        },
      });
    }

    res.json({
      id: sub.id,
      url: sub.url,
      contractAddress: sub.contractAddress,
      eventType: sub.eventType,
      topicSymbol: sub.topicSymbol,
      active: sub.active,
      verified: sub.verified,
      verifiedAt: sub.verifiedAt,
      updatedAt: sub.updatedAt,
    });
  }),
);

