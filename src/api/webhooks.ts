/**
 * @swagger
 * /webhooks/{id}/verify:
 *   post:
 *     summary: Verify ownership of a subscription's destination URL
 *     description: >
 *       Challenge/response handshake. The server sends a signed verification
 *       request containing a random `challenge` to the subscription URL. The
 *       endpoint must reply with HTTP 2xx and echo the challenge back as
 *       `{"challenge":"<value>"}` (plain-text echo is also accepted). On
 *       success the subscription is marked verified.
 *     security:
 *       - ApiKeyAuth: []
 *     tags: [Webhooks]
 *     parameters:
 *       - in: path
 *         name: id
 *         required: true
 *         schema: { type: string }
 *     responses:
 *       200:
 *         description: Subscription verified
 *       400:
 *         description: URL blocked, or the endpoint did not echo the challenge
 *       404:
 *         description: Not found or not owned by caller
 *       502:
 *         description: Destination unreachable or returned a non-2xx status
 *       401:
 *         description: API key required
 */
webhooksRouter.post(
  '/:id/verify',
  asyncHandler(async (req: Request, res: Response) => {
    const sub = await prismaRead.webhookSubscription.findFirst({
      where: { id: req.params.id, apiKeyId: req.apiKey!.id },
    });
    if (!sub) return res.status(404).json({ error: 'Subscription not found' });

    const challenge = generateVerificationToken();
    const body = buildVerificationBody(sub.id, challenge);
    const timestampMs = Date.now();

    // Persist only the digest of the challenge, with an expiry.
    await prisma.webhookSubscription.update({
      where: { id: sub.id },
      data: {
        verificationToken: hashVerificationToken(challenge),
        verificationExpiresAt: new Date(Date.now() + VERIFICATION_TOKEN_TTL_MS),
      },
    });

    const startMs = Date.now();
    try {
      const response = await safePost(
        sub.url,
        body,
        {
          'Content-Type': 'application/json',
          'X-Webhook-Timestamp': String(timestampMs),
          'X-Webhook-Signature': signWebhookBody(body, sub.secret),
        },
        REQUEST_TIMEOUT_MS,
      );
      const durationMs = Date.now() - startMs;

      if (response.status < 200 || response.status >= 300) {
        return res.status(502).json({
          verified: false,
          statusCode: response.status,
          durationMs,
          error: `Endpoint responded with HTTP ${response.status}`,
        });
      }

      if (!challengeMatches(response.data, challenge)) {
        return res.status(400).json({
          verified: false,
          statusCode: response.status,
          durationMs,
          error:
            'Endpoint did not echo the challenge. Respond with {"challenge":"<value>"} to complete verification.',
        });
      }

      const verifiedAt = new Date();
      await prisma.webhookSubscription.update({
        where: { id: sub.id },
        data: {
          verified: true,
          verifiedAt,
          verificationToken: null,
          verificationExpiresAt: null,
        },
      });

      return res.json({
        verified: true,
        subscriptionId: sub.id,
        verifiedAt,
        statusCode: response.status,
        durationMs,
      });
    } catch (err) {
      const durationMs = Date.now() - startMs;
      const blocked = err instanceof SsrfBlockedError;
      return res.status(blocked ? 400 : 502).json({
        verified: false,
        durationMs,
        error: blocked ? (err as Error).message : 'Verification request to the destination failed',
      });
    }
  }),
);

/**
 * @swagger
 * /webhooks/{id}/ping:
 *   post:
 *     summary: Send a synthetic test event to a subscription
 *     description: >
 *       Delivers a signed sample event to the subscription URL and records the
 *       attempt as a delivery. No retry is scheduled — this is a one-shot
 *       connectivity/signature test. The URL is SSRF-validated first.
 *     security:
 *       - ApiKeyAuth: []
 *     tags: [Webhooks]
 *     parameters:
 *       - in: path
 *         name: id
 *         required: true
 *         schema: { type: string }
 *     responses:
 *       200:
 *         description: Attempt completed (check `success`)
 *       400:
 *         description: Destination URL blocked by the SSRF guard
 *       404:
 *         description: Not found or not owned by caller
 *       401:
 *         description: API key required
 */
webhooksRouter.post(
  '/:id/ping',
  asyncHandler(async (req: Request, res: Response) => {
    const sub = await prismaRead.webhookSubscription.findFirst({
      where: { id: req.params.id, apiKeyId: req.apiKey!.id },
    });
    if (!sub) return res.status(404).json({ error: 'Subscription not found' });

    const result = await sendTestDelivery({
      subscriptionId: sub.id,
      url: sub.url,
      secret: sub.secret,
      payload: buildSampleEvent(sub),
      storeResponseBody: sub.storeResponseBody,
      responseRetentionDays: sub.responseRetentionDays,
    });

    res.status(result.blocked ? 400 : 200).json({ subscriptionId: sub.id, ...result });
  }),
);

/**
 * @swagger
 * /webhooks/{id}/preview:
 *   get:
 *     summary: Preview the exact payload and headers for a subscription
 *     description: >
 *       Returns the synthetic event envelope that a delivery would send, along
 *       with the signing headers (including a real signature computed with the
 *       subscription's secret for the sample body) so owners can test their
 *       verification code before going live.
 *     security:
 *       - ApiKeyAuth: []
 *     tags: [Webhooks]
 *     parameters:
 *       - in: path
 *         name: id
 *         required: true
 *         schema: { type: string }
 *     responses:
 *       200:
 *         description: Sample delivery envelope
 *       404:
 *         description: Not found or not owned by caller
 *       401:
 *         description: API key required
 */
webhooksRouter.get(
  '/:id/preview',
  asyncHandler(async (req: Request, res: Response) => {
    const sub = await prismaRead.webhookSubscription.findFirst({
      where: { id: req.params.id, apiKeyId: req.apiKey!.id },
    });
    if (!sub) return res.status(404).json({ error: 'Subscription not found' });

    const event = buildSampleEvent(sub);
    const rawBody = JSON.stringify({ event, attempt: 1 });
    const timestampMs = Date.now();

    res.json({
      subscriptionId: sub.id,
      delivery: {
        method: 'POST',
        url: sub.url,
        headers: {
          'Content-Type': 'application/json',
          'X-Webhook-Timestamp': String(timestampMs),
          'X-Webhook-Signature': signWebhookBody(rawBody, sub.secret),
        },
        body: { event, attempt: 1 },
      },
      rawBody,
      signatureFormat: 'sha256=<hex>',
      note: 'The signature is computed over rawBody. Verification snippets: GET /webhooks/sdk',
    });
  }),
);

/**
 * @swagger
 * /webhooks/{id}/deliveries:
 *   get:
 *     summary: Get delivery history for a webhook subscription
 *     description: Returns the last 50 delivery attempts including status, HTTP response, and retry schedule.
 *     security:
 *       - ApiKeyAuth: []
 *     tags: [Webhooks]
 *     parameters:
 *       - in: path
 *         name: id
 *         required: true
 *         schema: { type: string }
 *     responses:
 *       200:
 *         description: Delivery history
 *       404:
 *         description: Subscription not found or not owned by caller
 *       401:
 *         description: API key required
 */
webhooksRouter.get(
  '/:id/deliveries',
  asyncHandler(async (req: Request, res: Response) => {
    // Verify ownership before returning delivery history (#478).
    const sub = await prismaRead.webhookSubscription.findFirst({
      where: { id: req.params.id, apiKeyId: req.apiKey!.id },
      select: { id: true },
    });
    if (!sub) return res.status(404).json({ error: 'Subscription not found' });

    const deliveries = await prismaRead.webhookDelivery.findMany({
      where: { subscriptionId: sub.id },
      orderBy: { createdAt: 'desc' },
      take: 50,
    });
    res.json({ data: deliveries });
  }),
);
